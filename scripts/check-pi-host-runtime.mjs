import assert from 'node:assert/strict';
import { Socket } from 'node:net';
// This probe needs stdio only; reject every network request before transport.
Socket.prototype.connect = function () { throw new Error('Network disabled in compatibility probe'); };
globalThis.fetch = async () => { throw new Error('Fetch disabled in compatibility probe'); };
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
const hostRoot = resolve(process.argv[2]);
const root = mkdtempSync(join(tmpdir(), 'mcp-host-compat-'));
const agentDir = join(root, 'agent');
const cwd = join(root, 'project');
mkdirSync(agentDir); mkdirSync(cwd);
process.env.HOME = root;
process.env.XDG_CONFIG_HOME = join(root, 'config');
process.env.PI_CODING_AGENT_DIR = agentDir;
process.chdir(cwd);
process.env.PI_MCP_ADAPTER_TEST_AUTH_STORE = 'memory';
delete process.env.MCP_DIRECT_TOOLS;
const adapter = fileURLToPath(new URL('../', import.meta.url));
const configPath = join(root, 'mcp.json');
writeFileSync(configPath, JSON.stringify({mcpServers:{demo:{command:process.execPath,args:[join(adapter,'__tests__/fixtures/mcp-code-server.mjs')],lifecycle:'lazy',directTools:true}},settings:{scriptMode:true,showStatusIcon:false,hostConfigDiscovery:'off'}}));
process.env.PI_PACKAGE_DIR = hostRoot;
process.env.PI_OFFLINE = '1';
const host = await import(pathToFileURL(join(hostRoot, 'dist/index.js')));
const settingsManager = host.SettingsManager.inMemory();
const resourceLoader = new host.DefaultResourceLoader({cwd,agentDir,settingsManager,noExtensions:true,noContextFiles:true,noSkills:true,noPromptTemplates:true,noThemes:true,additionalExtensionPaths:[adapter]});
await resourceLoader.reload();
assert.deepEqual(resourceLoader.getExtensions().errors, []);
assert.equal(resourceLoader.getExtensions().extensions[0]?.resolvedPath, join(adapter, 'dist/index.js'));
const modelRuntime = await host.ModelRuntime.create({authPath:join(agentDir,'auth.json'),modelsPath:null,allowModelNetwork:false});
const {session} = await host.createAgentSession({cwd,agentDir,resourceLoader,settingsManager,modelRuntime,sessionManager:host.SessionManager.inMemory(cwd)});
const errors=[];
session.extensionRunner.setFlagValue('mcp-config',configPath);
try {
 await session.bindExtensions({mode:'print',onError:error=>errors.push(error)});
 const call = async (name,args) => {
  const tool=session.agent.state.tools.find(t=>t.name===name);
  assert.ok(tool,`Missing active ${name}`);
  return tool.execute('compat-'+name,args,new AbortController().signal);
 };
 const before=session.getActiveToolNames();
 console.error(JSON.stringify({before,all:session.getAllTools().map(t=>t.name),errors,extensions:resourceLoader.getExtensions().extensions.map(e=>({path:e.path,tools:[...e.tools.keys()]}))}));
 assert.ok(before.includes('mcp')); assert.ok(before.includes('mcp_script'));
 assert.ok(!before.includes('demo_echo'));
 const status=await call('mcp',{});
 assert.deepEqual(status.details.servers.map(server => server.name), ['demo']);
 const connect=await call('mcp',{connect:'demo'});
 assert.ok(session.getActiveToolNames().includes('demo_echo'));
 const direct=await call('demo_echo',{value:'direct-host-ok'});
 assert.match(JSON.stringify(direct),/direct-host-ok/);
 const proxy=await call('mcp',{tool:'demo_echo',args:{value:'proxy-host-ok'}});
 assert.match(JSON.stringify(proxy),/proxy-host-ok/);
 const script=await call('mcp_script',{code:'const found = await tools.search({query:"echo"}); const result = await tools.demo_echo({value:"script-host-ok"}); emit({found,result});'});
 assert.match(JSON.stringify(script),/script-host-ok/);
 assert.match(JSON.stringify(script),/"ok":true/);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({host:hostRoot,compiledEntrypoint:join(adapter,'dist/index.js'),before,after:session.getActiveToolNames(),status,connect,direct,proxy,script},null,2));
} finally {
 await session.extensionRunner.emit({type:'session_shutdown',reason:'compat-test'});
 session.dispose(); rmSync(root,{recursive:true,force:true});
}
